const CURRENCY_BY_COUNTRY = Object.fromEntries(COUNTRIES.map((c) => [c[0], c[2]]))

// Two-letter country code (Cloudflare's CF-IPCountry) -> currency. Anything not listed gets USD.
export function currencyForCountry(country) {
  return CURRENCY_BY_COUNTRY[String(country || '').toUpperCase()] || 'USD'
}

export function isKnownCountry(country) {
  return Object.prototype.hasOwnProperty.call(CURRENCY_BY_COUNTRY, String(country || '').toUpperCase())
}

// US dollars -> whole units of the shopper's currency. USD keeps cents (the existing prices).
export function localAmount(usd, currency) {
  const rate = RATES[currency]
  if (!rate || currency === 'USD') return usd
  return Math.round(usd * rate)
}
